import type { DayForecast, ExperimentResult, HistoryReconstruction, ImportReport, Layout, VolumeSpec } from '../domain/types';
import { buildTakeaway } from '../sim/takeaway';

/**
 * Optional "AI review". Gemini only rewords facts the deterministic engine already computed; it never
 * receives raw rows and its text never feeds back into any number. Available only on the dev server,
 * where a proxy holds the key (see vite.config.ts).
 */
export const aiReviewAvailable = import.meta.env.VITE_AI_REVIEW === 'on';
export const AI_DISCLAIMER = 'Note: Generated by Gemini AI based on your simulation data. Always verify against physical room constraints.';
export const AI_WEEK_DISCLAIMER = 'Note: AI operational suggestion based on your 7-day radar context. Verify against actual staff availability.';

/** The outlook facts Gemini may use for the weekly memo: the forecast's own numbers and labels, nothing derived. */
export interface WeekFacts {
  days: { date: string; weekday: string; partiesExpected: number; partiesRange: [number, number]; typicalForWeekday: number | null;
    weather: string | null; weatherIsLive: boolean; events: { name: string; assumedDemandChangePct: number | null }[] }[];
}
const WEEKDAYS = ['sunday', 'monday', 'tuesday', 'wednesday', 'thursday', 'friday', 'saturday'];
export function buildWeekFacts(days: DayForecast[]): WeekFacts {
  return {
    days: days.filter((d) => d.parties).map((d) => {
      const w = d.factors.find((f) => f.factor === 'weather');
      return {
        date: d.date, weekday: WEEKDAYS[d.dow], partiesExpected: d.parties!.mid, partiesRange: [d.parties!.low, d.parties!.high],
        typicalForWeekday: d.typicalParties !== undefined ? Math.round(d.typicalParties) : null,
        weather: w ? w.label : null, weatherIsLive: Boolean(w?.reason.includes('live NWS')),
        events: d.factors.filter((f) => f.factor !== 'weather').map((f) => ({
          name: f.label, assumedDemandChangePct: f.evidence === 'Assumed' ? Math.round((f.multiplier - 1) * 100) : null,
        })),
      };
    }),
  };
}
// Tried in order; Google retires model names often, and a busy model answers 503.
const MODELS = ['gemini-3.5-flash', 'gemini-3.8-flash', 'gemini-flash-latest'];

export interface AiReviewInput {
  dataset: { checks: number; nights: number; dateRange: [string, string] | null; synthetic: boolean };
  history: { capacityLimitedNights: number; nights: number; busiestWindow: string | null; partiesOfTwoOrFewerPct: number };
  // absent for the data-only summary on Data Review
  layouts?: { current: string; alternative: string };
  demand?: string;
  takeaway?: string;
  metrics?: { metric: string; unit: string; current: number; alternative: number; delta: number; band: [number, number]; clear: boolean }[];
}

const r1 = (v: number) => Math.round(v * 10) / 10;
const clock = (min: number) => {
  const h = Math.floor(min / 60) % 24, m = min % 60;
  return `${((h + 11) % 12) + 1}:${String(m).padStart(2, '0')} ${h < 12 ? 'am' : 'pm'}`;
};
const describeLayout = (l: Layout) => {
  const byCap = new Map<number, number>();
  l.tables.forEach((t) => byCap.set(t.capacity, (byCap.get(t.capacity) ?? 0) + 1));
  const mix = [...byCap].sort((a, b) => a[0] - b[0]).map(([c, n]) => `${n} ${c}-tops`).join(', ');
  return `${l.name}: ${mix}; ${l.joins.length} combinable pairs`;
};

/** Collects the engine's own numbers into the only facts Gemini sees. Deterministic. */
export function buildAiReviewInput(args: {
  report: ImportReport; reconstruction: HistoryReconstruction | null; result: ExperimentResult | null;
  current: Layout; alternative: Layout; volume: VolumeSpec; altName: string;
}): AiReviewInput {
  const { report, reconstruction: rec, result } = args;
  let busiestWindow: string | null = null;
  if (rec && rec.profile.length) {
    const peak = Math.max(...rec.profile.map((p) => p.meanTableUseGuests));
    const busy = rec.profile.filter((p) => p.meanTableUseGuests >= 0.85 * peak);
    if (peak > 0 && busy.length) busiestWindow = `${clock(busy[0].minute)} – ${clock(busy[busy.length - 1].minute + rec.binMin)}`;
  }
  const parties = rec?.partySizeCounts.reduce((s, p) => s + p.parties, 0) ?? 0;
  const small = rec?.partySizeCounts.filter((p) => p.size <= 2).reduce((s, p) => s + p.parties, 0) ?? 0;
  const v = args.volume;
  return {
    dataset: { checks: report.rowsUsed, nights: report.nightsByDow.reduce((a, b) => a + b, 0), dateRange: report.dateRange ?? null, synthetic: report.isSample },
    history: {
      capacityLimitedNights: rec?.capacityLimitedNights ?? 0, nights: rec?.nights.length ?? 0, busiestWindow,
      partiesOfTwoOrFewerPct: parties ? Math.round((100 * small) / parties) : 0,
    },
    ...(result ? {
      layouts: { current: describeLayout(args.current), alternative: describeLayout(args.alternative) },
      demand: result.demandBanner,
      takeaway: buildTakeaway(result, args.altName).headline,
      metrics: result.metrics.flatMap((m) => {
        const p = m.paired[0], a = m.perScenario['current'], b = m.perScenario['alternative'];
        return p && a && b ? [{ metric: m.label, unit: m.unit, current: r1(a.mean), alternative: r1(b.mean), delta: r1(p.meanDelta), band: [r1(p.p10), r1(p.p90)] as [number, number], clear: !p.noClearDifference }] : [];
      }),
    } : {}),
  };
}

export type AiTask = { kind: 'review' } | { kind: 'data' } | { kind: 'ask'; question: string } | { kind: 'week'; week: WeekFacts };

function prompt(input: AiReviewInput, task: AiTask): string {
  if (task.kind === 'week') {
    return [
      'You are an operations advisor for an independent full-service restaurant.',
      'Write exactly 2 sentences: a prep and staffing memo for the coming week. Name the busiest night with its expected parties and range, its weather and any events, and the usual busiest window.',
      'You may suggest qualitative actions (an extra busser, earlier prep, confirming large reservations). Never invent numbers, percentages, counts or times that are not in FACTS.',
      'Weather and events without an assumed change do not change the forecast; do not say they will raise demand. Plain text, no markdown.',
      `FACTS: ${JSON.stringify({ week: task.week, busiestWindow: input.history.busiestWindow, synthetic: input.dataset.synthetic })}`,
    ].join('\n');
  }
  const instruction = task.kind === 'data'
    ? 'Write exactly 2 sentences summarizing what this history shows: busiest window, how many nights were capacity-limited (90%+ of tables in use at the peak), and the small-party share. Do not recommend a layout.'
    : task.kind === 'ask'
    ? `Answer the owner's question in at most 90 words: "${task.question.slice(0, 300)}". If the facts cannot answer it, say what extra data would be needed.`
    : 'Write at most 110 words: first what the history shows (busiest window, capacity-limited nights, small-party share), then a line starting "What you should do:" recommending the alternative layout only for effects marked clear=true.';
  return [
    'You are an operations advisor for an independent full-service restaurant.',
    'Use ONLY the numbers in FACTS. Never compute, estimate or invent new numbers, percentages, days, costs or times.',
    'Effects with clear=false must be described as "no clear difference". These are modeled results under stated assumptions, not guarantees.',
    'Plain text, no markdown, no headings.',
    instruction,
    `FACTS: ${JSON.stringify(input)}`,
  ].join('\n');
}

export async function generateAiReview(input: AiReviewInput, task: AiTask = { kind: 'review' }): Promise<string> {
  if (!aiReviewAvailable) throw new Error('ai review is not configured');
  const body = JSON.stringify({ contents: [{ role: 'user', parts: [{ text: prompt(input, task) }] }], generationConfig: { temperature: 0.2, maxOutputTokens: 4096, thinkingConfig: { thinkingLevel: 'low' } } });
  let res: Response | null = null;
  const busy = (r: Response | null) => !r || [404, 429, 503].includes(r.status);
  // Two passes over the model list; Google's "high demand" 503s usually clear within seconds.
  for (let pass = 0; pass < 2 && busy(res); pass++) {
    if (pass) await new Promise((r) => setTimeout(r, 2500));
    for (const model of MODELS) {
      res = await fetch(`/gemini/v1beta/models/${model}:generateContent`, {
        method: 'POST', headers: { 'Content-Type': 'application/json' }, body, signal: AbortSignal.timeout(30000),
      });
      if (!busy(res)) break;
    }
  }
  if (!res || !res.ok) throw new Error(`gemini returned ${res?.status ?? 'no response'}`);
  const data = await res.json();
  const cand = data?.candidates?.[0];
  if (cand?.finishReason && cand.finishReason !== 'STOP') throw new Error(`gemini stopped early (${String(cand.finishReason).toLowerCase()})`);
  const text: string = (cand?.content?.parts ?? []).filter((p: { thought?: boolean }) => !p.thought).map((p: { text?: string }) => p.text ?? '').join('').trim();
  if (!text) throw new Error('gemini returned no text');
  return text;
}
